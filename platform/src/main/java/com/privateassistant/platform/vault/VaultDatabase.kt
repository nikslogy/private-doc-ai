package com.privateassistant.platform.vault

import androidx.room.ColumnInfo
import androidx.room.Dao
import androidx.room.Database
import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Fts4
import androidx.room.FtsOptions
import androidx.room.Index
import androidx.room.Insert
import androidx.room.PrimaryKey
import androidx.room.Query
import androidx.room.RoomDatabase
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

@Entity(
    tableName = "documents",
    indices = [Index(value = ["sha256"], unique = true), Index(value = ["folderId"])],
)
internal data class DocumentEntity(
    @PrimaryKey val id: String,
    val displayName: String,
    val mimeType: String,
    val sizeBytes: Long,
    val importedAtEpochMillis: Long,
    val sha256: String,
    val revisionId: String = id,
    @ColumnInfo(defaultValue = "0") val pageCount: Int = 0,
    @ColumnInfo(defaultValue = "'NOT_INDEXED'") val indexState: String = VaultIndexState.NOT_INDEXED.name,
    /** Null means "not in a folder". Folder names live only in the encrypted database. */
    val folderId: String? = null,
    /** A derivative (compressed copy, page image, passport photo) records the document it came from. */
    val parentDocumentId: String? = null,
) {
    fun toDocument() = VaultDocument(
        id, displayName, mimeType, sizeBytes, importedAtEpochMillis, sha256, revisionId,
        pageCount, enumValueOf(indexState), folderId, parentDocumentId,
    )
}

@Entity(tableName = "folders")
internal data class FolderEntity(
    @PrimaryKey val id: String,
    val name: String,
    val createdAtEpochMillis: Long,
) {
    fun toFolder() = VaultFolder(id, name, createdAtEpochMillis)
}

@Dao
internal interface FolderDao {
    @Query("SELECT * FROM folders ORDER BY name COLLATE NOCASE ASC, id ASC")
    fun all(): List<FolderEntity>

    @Query("SELECT * FROM folders WHERE id = :id LIMIT 1")
    fun find(id: String): FolderEntity?

    @Query("SELECT COUNT(*) FROM folders")
    fun count(): Int

    @Insert
    fun insert(folder: FolderEntity)

    @Query("UPDATE folders SET name = :name WHERE id = :id")
    fun rename(id: String, name: String)

    @Query("DELETE FROM folders WHERE id = :id")
    fun delete(id: String)
}

@Entity(
    tableName = "page_evidence",
    foreignKeys = [ForeignKey(
        entity = DocumentEntity::class, parentColumns = ["id"], childColumns = ["documentId"],
        onDelete = ForeignKey.CASCADE,
    )],
    indices = [Index(value = ["documentId", "pageNumber"], unique = true)],
)
internal data class PageEvidenceEntity(
    @PrimaryKey(autoGenerate = true) @ColumnInfo(name = "rowid") val rowId: Long = 0,
    val documentId: String,
    val revisionId: String,
    val pageNumber: Int,
    val text: String,
    val width: Int?,
    val height: Int?,
    val method: String?,
    val extractorVersion: String,
    val state: String,
)

/**
 * The ASCII-encoded tokens are generated by the same core tokenizer as the query. This avoids
 * SQLite's Unicode-version/combining-mark differences without modifying evidence or its offsets.
 * It is an ordinary FTS table; all row insertion/removal occurs with evidence in one transaction.
 */
@Fts4(tokenizer = FtsOptions.TOKENIZER_SIMPLE)
@Entity(tableName = "page_search")
internal data class PageSearchEntity(
    @PrimaryKey @ColumnInfo(name = "rowid") val rowId: Long,
    val searchTerms: String,
)

@Entity(
    tableName = "page_spans",
    primaryKeys = ["pageId", "ordinal"],
    foreignKeys = [ForeignKey(
        entity = PageEvidenceEntity::class, parentColumns = ["rowid"], childColumns = ["pageId"],
        onDelete = ForeignKey.CASCADE,
    )],
)
internal data class PageSpanEntity(
    val pageId: Long,
    val ordinal: Int,
    val startUtf16: Int,
    val endUtf16: Int,
    val kind: String,
    val left: Float?,
    val top: Float?,
    val right: Float?,
    val bottom: Float?,
)

@Dao
internal interface DocumentDao {
    @Query("SELECT * FROM documents ORDER BY importedAtEpochMillis DESC, id ASC")
    fun all(): List<DocumentEntity>

    @Query("SELECT * FROM documents WHERE id = :id LIMIT 1")
    fun find(id: String): DocumentEntity?

    @Query("SELECT * FROM documents WHERE sha256 = :sha256 LIMIT 1")
    fun findDigest(sha256: String): DocumentEntity?

    @Query("SELECT COUNT(*) FROM documents")
    fun count(): Int

    @Insert
    fun insert(document: DocumentEntity)

    @Query("UPDATE documents SET pageCount = :pageCount, indexState = :state WHERE id = :id")
    fun updateIndex(id: String, pageCount: Int, state: String)

    // Native calls may have been interrupted by process death. Recovery never starts OCR itself.
    @Query("UPDATE documents SET indexState = 'FAILED' WHERE indexState = 'INDEXING'")
    fun recoverInterruptedIndexing()

    @Query("DELETE FROM documents WHERE id = :id")
    fun delete(id: String)

    @Query("UPDATE documents SET folderId = :folderId WHERE id = :id")
    fun move(id: String, folderId: String?)

    @Query("UPDATE documents SET displayName = :name WHERE id = :id")
    fun rename(id: String, name: String)

    /** Deleting a folder never deletes its documents; they return to the unfiled list. */
    @Query("UPDATE documents SET folderId = NULL WHERE folderId = :folderId")
    fun unfile(folderId: String)

    /** Derivatives stay valid files on their own after the parent is deleted. */
    @Query("UPDATE documents SET parentDocumentId = NULL WHERE parentDocumentId = :parentId")
    fun detachChildren(parentId: String)
}

@Dao
internal interface EvidenceDao {
    @Query("SELECT * FROM page_evidence WHERE documentId = :documentId ORDER BY pageNumber ASC")
    fun pages(documentId: String): List<PageEvidenceEntity>

    @Query("SELECT * FROM page_spans WHERE pageId = :pageId ORDER BY ordinal ASC")
    fun spans(pageId: Long): List<PageSpanEntity>

    @Insert
    fun insertPage(page: PageEvidenceEntity): Long

    @Insert
    fun insertSpans(spans: List<PageSpanEntity>)

    @Insert
    fun insertSearch(page: PageSearchEntity)

    @Query("SELECT p.rowid FROM page_evidence AS p JOIN page_search ON p.rowid = page_search.rowid " +
        "WHERE page_search MATCH :match ORDER BY p.documentId ASC, p.pageNumber ASC LIMIT :limit")
    fun searchIds(match: String, limit: Int): List<Long>

    @Query("SELECT * FROM page_evidence WHERE rowid = :rowId LIMIT 1")
    fun findPage(rowId: Long): PageEvidenceEntity?

    @Query("DELETE FROM page_search WHERE rowid IN (SELECT rowid FROM page_evidence WHERE documentId = :documentId)")
    fun deleteSearch(documentId: String)

    @Query("DELETE FROM page_evidence WHERE documentId = :documentId")
    fun deletePages(documentId: String)
}

@Database(
    entities = [DocumentEntity::class, PageEvidenceEntity::class, PageSpanEntity::class, PageSearchEntity::class,
        FolderEntity::class],
    version = 3,
    exportSchema = true,
)
internal abstract class VaultDatabase : RoomDatabase() {
    abstract fun documents(): DocumentDao
    abstract fun evidence(): EvidenceDao
    abstract fun folders(): FolderDao

    companion object {
        /** Adds only encrypted metadata; v1 originals and their immutable identity stay unchanged. */
        val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL("ALTER TABLE documents ADD COLUMN pageCount INTEGER NOT NULL DEFAULT 0")
                db.execSQL("ALTER TABLE documents ADD COLUMN indexState TEXT NOT NULL DEFAULT 'NOT_INDEXED'")
                db.execSQL("CREATE TABLE IF NOT EXISTS page_evidence (rowid INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, " +
                    "documentId TEXT NOT NULL, revisionId TEXT NOT NULL, pageNumber INTEGER NOT NULL, text TEXT NOT NULL, " +
                    "width INTEGER, height INTEGER, method TEXT, extractorVersion TEXT NOT NULL, state TEXT NOT NULL, " +
                    "FOREIGN KEY(documentId) REFERENCES documents(id) ON UPDATE NO ACTION ON DELETE CASCADE)")
                db.execSQL("CREATE UNIQUE INDEX IF NOT EXISTS index_page_evidence_documentId_pageNumber ON page_evidence(documentId, pageNumber)")
                db.execSQL("CREATE TABLE IF NOT EXISTS page_spans (pageId INTEGER NOT NULL, ordinal INTEGER NOT NULL, " +
                    "startUtf16 INTEGER NOT NULL, endUtf16 INTEGER NOT NULL, kind TEXT NOT NULL, " +
                    "`left` REAL, top REAL, `right` REAL, bottom REAL, PRIMARY KEY(pageId, ordinal), " +
                    "FOREIGN KEY(pageId) REFERENCES page_evidence(rowid) ON UPDATE NO ACTION ON DELETE CASCADE)")
                // Room omits the default SIMPLE tokenizer option; its schema validator compares
                // FTS option strings, so explicitly adding the equivalent default fails migration.
                db.execSQL("CREATE VIRTUAL TABLE IF NOT EXISTS page_search USING FTS4(searchTerms TEXT NOT NULL)")
            }
        }

        /** Adds folders and derivative parent links. Existing documents stay unfiled and unchanged. */
        val MIGRATION_2_3 = object : Migration(2, 3) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL("CREATE TABLE IF NOT EXISTS folders (id TEXT NOT NULL, name TEXT NOT NULL, " +
                    "createdAtEpochMillis INTEGER NOT NULL, PRIMARY KEY(id))")
                db.execSQL("ALTER TABLE documents ADD COLUMN folderId TEXT")
                db.execSQL("ALTER TABLE documents ADD COLUMN parentDocumentId TEXT")
                db.execSQL("CREATE INDEX IF NOT EXISTS index_documents_folderId ON documents(folderId)")
            }
        }
    }
}
